HEADER = '''# OpenGL enumerants and the runtime's window, key, mouse, and cursor constants.
#
# Generated by `scripts/gen-gl-constants.py`; extend the tables there rather than
# editing this file. `GL_*` names are unsigned because the runtime's enum
# parameters are `u32`; the window/input names are signed because those
# parameters are `i32`. Constants with the same value (for example `GL_ZERO`,
# `GL_FALSE`, and `GL_NONE`) are kept separate so call sites read like the
# specification.
'''


def section(title: str, rows: list[tuple[str, int]], type_name: str) -> str:
    lines = [f"# --- {title} " + "-" * max(0, 74 - len(title))]
    for name, value in rows:
        literal = str(value) if value < 10 else f"0x{value:04X}"
        lines.append(f"const {name}: {type_name} = {literal}")
    return "\n".join(lines)


def main() -> int:
    parts = [HEADER.rstrip(), ""]
    parts.append(section("OpenGL enumerants, grouped as in the specification", GL, "u32"))
    parts.append("")
    parts.append(section("window, cursor, mouse, and modifier values", WINDOW, "i32"))
    parts.append("")
    parts.append(section("keys (platform virtual-key codes)", KEYS, "i32"))
    text = "\n".join(parts).rstrip() + "\n"

    output = ROOT / "stdlib" / "gl" / "constants.sere"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8", newline="\n")
    names = len(GL) + len(WINDOW) + len(KEYS)
    print(f"wrote {output.relative_to(ROOT)} ({names} constants, {len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
