"""Regenerate Wavio's private Sere ABI declarations from its native header."""
from pathlib import Path
import re
import keyword

root = Path(__file__).resolve().parents[1]
header = (root / "runtime/wavio/wavio.h").read_text()
header = re.sub(r"/\*.*?\*/", "", header, flags=re.S)
types = {"int32_t": "i32", "int64_t": "i64", "double": "f64", "void": "void"}

def sere_type(native):
    return "Ptr[i8]" if native.endswith("*") else types[native]

lines = ['# Generated by scripts/gen-wavio-bindings.py. Native handles require explicit close.', '']
for ret, name, args in re.findall(r"([\w]+\*?)\s+(wavio_\w+)\(([^)]*)\);", header):
    if name in {"wavio_error_message", "wavio_device_name"}:
        continue
    params = []
    args = re.sub(r"\s+", " ", args).strip()
    parts = args.split(", ") if args != "void" else []
    skip_length = False
    for part in parts:
        ty, arg = part.rsplit(" ", 1)
        if keyword.iskeyword(arg):
            arg += "_value"
        if skip_length:
            assert ty == "int64_t" and arg == "length"
            skip_length = False
            continue
        if ty == "const char*":
            ty = "str"
            skip_length = True
        else:
            ty = sere_type(ty)
        params.append(f"{arg}: {ty}")
    lines += [f'extern "C" "{name}"',
              f'def _{name[6:]}({", ".join(params)}) -> {sere_type(ret)}',
              '"""Private native binding; see runtime/wavio/wavio.h for the contract."""', '']
lines += ['extern "C" "sere_wavio_error_message"',
          'def _error_message(code: i32) -> str', '"""Copy a native status description."""', '',
          'extern "C" "sere_wavio_device_name"',
          'def _device_name(c: Ptr[i8], capture: i32, index: i32) -> str',
          '"""Copy a device name into Sere-owned memory."""', '']
(root / "stdlib/wavio/_native.sere").write_text("\n".join(lines), newline="\n")
for path in (root / "stdlib/wavio").glob("*.sere"):
    source = path.read_text()
    if "from wavio._native import " in source:
        names = sorted(set(re.findall(r"\b(_[a-z][a-z_0-9]+)\(", source)))
        source = re.sub(r"from wavio\._native import [^\n]+", "from wavio._native import " + ", ".join(names), source)
        path.write_text(source, newline="\n")
