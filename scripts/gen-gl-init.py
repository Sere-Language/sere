"""Generate stdlib/gl/__init__.sere, the barrel that assembles the binding.

Every part of the binding lives in its own module under `stdlib/gl/`. The barrel
star-imports each part and then re-exports every public top-level name it finds,
so `import gl` is enough to reach the whole surface while the parts stay small
enough to navigate.

Run from the repository root:

    py scripts/gen-gl-init.py

The script is a build-time convenience, not part of the compiler: the generated
file is committed, and regenerating it after adding a module or a public name
keeps `gl.__exports__` in step with the sources.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "stdlib" / "gl"
OUTPUT = PACKAGE / "__init__.sere"

# The parts, in the order they are imported. `__init__` is the barrel itself and
# `types` only holds aliases, but both are listed so the output is deterministic.
PARTS = [
    "constants",
    "types",
    "info",
    "errors",
    "state",
    "immediate",
    "shaders",
    "buffers",
    "textures",
    "framebuffer",
    "window",
]

# Top-level declarations that become part of `gl`. Enum and struct bodies are
# indented, so anchoring on the first column keeps their variants out.
DECLARATIONS = [
    re.compile(r"^def ([A-Za-z_][A-Za-z0-9_]*)"),
    re.compile(r"^class ([A-Za-z_][A-Za-z0-9_]*)"),
    re.compile(r"^const ([A-Za-z_][A-Za-z0-9_]*)"),
    re.compile(r"^type ([A-Za-z_][A-Za-z0-9_]*)"),
    re.compile(r"^enum ([A-Za-z_][A-Za-z0-9_]*)"),
    re.compile(r"^struct ([A-Za-z_][A-Za-z0-9_]*)"),
]

HEADER = """\
# The OpenGL binding, assembled from the parts in this directory.
#
# Import with: import gl
#
# The runtime loads a driver and a context through the window API, and this
# package exposes the rest of the API in the usual OpenGL shape: one function
# per entry point, `GL_*` names for the enumerants, and small classes for the
# objects that need a lifetime (Window, Program, Shader, Buffer, VertexArray,
# Texture, Framebuffer, Renderbuffer).
#
# This file is generated by `scripts/gen-gl-init.py`; edit the parts, then
# regenerate rather than editing the export list by hand.
#
# The parts are:"""


def module_docstring(part: str) -> str:
    """Return the first comment line of a part, for the module map."""
    text = (PACKAGE / f"{part}.sere").read_text(encoding="utf-8")
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("# "):
            return stripped[2:].strip()
    return ""


def collect(part: str) -> list[str]:
    """Return the public top-level names declared in one part, in source order."""
    text = (PACKAGE / f"{part}.sere").read_text(encoding="utf-8")
    names: list[str] = []
    for line in text.splitlines():
        for pattern in DECLARATIONS:
            match = pattern.match(line)
            if match is None:
                continue
            name = match.group(1)
            if not name.startswith("_") and name not in names:
                names.append(name)
            break
    return names


def main() -> int:
    parts = [part for part in PARTS if (PACKAGE / f"{part}.sere").exists()]
    missing = [part for part in PARTS if part not in parts]
    if missing:
        print(f"warning: no source for {', '.join(missing)}")

    lines = [HEADER]
    width = max(len(part) for part in parts)
    for part in parts:
        lines.append(f"#   gl.{part.ljust(width)}  {module_docstring(part)}")
    lines.append("")
    for part in parts:
        lines.append(f"from gl.{part} import *")
    lines.append("")

    seen: dict[str, str] = {}
    duplicates: list[str] = []
    exports: list[str] = []
    for part in parts:
        for name in collect(part):
            if name in seen:
                duplicates.append(f"{name} ({seen[name]} and {part})")
                continue
            seen[name] = part
            exports.append(name)

    lines.append(f"__exports__ = [{exports[0]}]")
    for index in range(1, len(exports), 6):
        chunk = exports[index:index + 6]
        lines.append(f"__exports__ += [{', '.join(chunk)}]")
    lines.append("")

    OUTPUT.write_text("\n".join(lines).replace("\r\n", "\n"), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(exports)} exports from {len(parts)} parts)")
    for duplicate in duplicates:
        print(f"  duplicate skipped: {duplicate}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
